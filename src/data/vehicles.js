// Generate years dynamically from launch year to current year (2026)
export const getYearsForModel = (vehicleType, brand, modelId) => {
  const models = vehiclesData[vehicleType]?.models?.[brand];
  if (!models) return [];
  
  const model = models.find(m => m.id === modelId);
  if (!model || !model.launchYear) return [];
  
  const launchYear = model.launchYear;
  const currentYear = 2026;
  const years = [];
  
  for (let year = currentYear; year >= launchYear; year--) {
    years.push(year);
  }
  
  return years;
};

